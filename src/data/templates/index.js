// src/data/templates/index.js
// These are the actual rule files Brokeflow generates FOR the student's project.
// They are source data — NOT the rules for building Brokeflow itself.
// The Configurator reads from here and assembles a ZIP for the user.

import { STACK_RULES, SCENARIO_RULES, WINDOW_RULES, TEAM_RULES, DEPLOY_BLOCKS, FRAMEWORK_RULES, ADDITIONAL_TOOL_RULES } from './rules'
import { detectStackFromFramework, buildToolsGuide, buildQuickStart, buildGitignore, buildEnvExample, buildViteConfig } from './utils'

// Raw template markdown files imported via Vite raw query suffix
import contributingMd from './markdown/contributing.md?raw'
import designTokensMd from './markdown/design-tokens.md?raw'
import sdgPlaybookMd from './markdown/sdg-playbook.md?raw'
import hackathonModeMd from './markdown/hackathon-mode.md?raw'

export function buildFiles({ stack, framework, scenario, window: win, tools, team, deploy }) {
  const fw = framework?.trim() || stack

  // Resolve a useful stack id when user picked 'other'
  const resolvedStack = stack === 'other' ? detectStackFromFramework(framework) : stack

  // ─── FILE ASSEMBLY ─────────────────────────────────────────────────────────

  const teamSection  = team   ? '\n' + (TEAM_RULES[team]            || '') : ''
  const deployBlock  = deploy ? (DEPLOY_BLOCKS[deploy] || DEPLOY_BLOCKS.none) : ''
  
  // Conditional framework rules detection
  const fwKey = fw.toLowerCase()
  let frameworkRules = ''
  if ((resolvedStack === 'frontend' || resolvedStack === 'fullstack') && fwKey.includes('svelte')) {
    frameworkRules = '\n' + FRAMEWORK_RULES.sveltekit
  } else if (resolvedStack === 'backend' && fwKey.includes('rust')) {
    frameworkRules = '\n' + FRAMEWORK_RULES.rust
  }

  // Conditional DeepSeek rules detection
  const deepseekRules = tools.includes('deepseek') ? '\n' + ADDITIONAL_TOOL_RULES.deepseek : ''

  const toolsGuide   = buildToolsGuide(tools)

  const agentsMd = `# AGENTS.md
# Brokeflow — Generated Config
# Stack: ${fw} | Scenario: ${scenario} | Window: ${win} | Tools: ${tools.join(', ')}${team ? ' | Team: ' + team : ''}${deploy ? ' | Deploy: ' + deploy : ''}
#
# References:
#   CLAUDE.md spec:    https://docs.anthropic.com/en/docs/claude-code/memory
#   Karpathy:          https://x.com/karpathy
#   Copilot custom:    https://docs.github.com/en/copilot/customizing-copilot/adding-custom-instructions-for-github-copilot

## THE 4 LAWS (Karpathy-Derived)
1. THINK BEFORE CODING — print [ASSUMPTIONS & TRADEOFFS] before any non-trivial block. Wait for confirmation if it touches architecture.
2. SIMPLICITY FIRST — minimum lines required. No unrequested abstractions, no premature packages, no over-engineering.
3. SURGICAL CHANGES — modify ONLY the exact file/function requested. No silent refactors. No "while I'm here" edits.
4. GOAL-DRIVEN EXECUTION — state verification steps BEFORE writing code. Loop until all assertions pass.

## ALWAYS ENFORCE
- If the AI outputs // TODO: implement later or // ... rest of component — that is an incomplete response. Reject it and re-prompt: "Write the full implementation, no placeholders."
- All secrets and API keys must be loaded exclusively from environment variables (e.g. process.env or os.environ). If you need to add a new private credential, append its variable name (without the value!) to '.env.example' and add the actual value to your local '.env'. Never write real API keys inside codebase files, comments, or documentation.
- One AI prompt = one goal. Never batch multiple objectives in a single prompt. Batched prompts produce batched mistakes.

## PROMPT FORMAT
  [FILE: path/to/file]
  [GOAL: single specific action]
  [LAW: most relevant law]

  Your instruction here.
${STACK_RULES[resolvedStack] || STACK_RULES.other}${frameworkRules}${deepseekRules}
${SCENARIO_RULES[scenario] || ''}
${WINDOW_RULES[win] || ''}${teamSection}${toolsGuide}
`

  const files = {
    'AGENTS.md': agentsMd,
    '.env.example': buildEnvExample(resolvedStack, tools, deploy),
    'README.md': `# Project — Brokeflow Config Applied
> Stack: ${fw} | Scenario: ${scenario} | Time Window: ${win}

## AI Workspace
This project uses Brokeflow guardrails. See AGENTS.md for the 4 Laws.

## Quick Start
${buildQuickStart(resolvedStack, framework)}

${deployBlock}
${scenario === 'sdg-hack' ? '\n## SDG Goal\n_State which SDG goal this addresses and how._\n' : ''}
## Contribute
This config was generated by [Brokeflow](https://github.com/brokeflow/brokeflow).

Found a rule that saved your hackathon? Broke a rule and learned why it exists?
Share your experience:
- Star and fork: https://github.com/brokeflow/brokeflow
- Submit a rule improvement: https://github.com/brokeflow/brokeflow/issues
- Share your AGENTS.md setup in Discussions
`,
    '.gitignore': buildGitignore(resolvedStack),
    'CONTRIBUTING.md': contributingMd,
  }

  if (tools.includes('claude'))
    files['CLAUDE.md'] = agentsMd.replace('# AGENTS.md', '# CLAUDE.md')

  if (tools.includes('copilot'))
    files['.github/copilot-instructions.md'] = agentsMd

  if (tools.includes('cursor'))
    files['.cursorrules'] = agentsMd

  if (tools.includes('aider'))
    files['.aider.instruction.md'] = agentsMd

  if (tools.includes('windsurf'))
    files['.windsurfrules'] = agentsMd

  if (scenario === 'sdg-hack') {
    files['SDG.md'] = sdgPlaybookMd
  }

  if (['frontend', 'fullstack'].includes(resolvedStack)) {
    files['frontend/DESIGN_TOKENS.md'] = designTokensMd

    files['shared/mockDb.js'] = `// shared/mockDb.js
// Zero-config localStorage wrapper — swap for Supabase/Firebase/Postgres post-demo
// Usage: db.save('users', { name: 'Alice' }) → returns saved record with id + createdAt
export const db = {
  save: (col, data) => {
    try {
      const records = JSON.parse(localStorage.getItem(col) || '[]')
      const rec = { id: Date.now().toString(), createdAt: new Date().toISOString(), ...data }
      records.push(rec)
      localStorage.setItem(col, JSON.stringify(records))
      return rec
    } catch (e) { console.error('[MockDB] save fail', e); return null }
  },
  get:    (col) => { try { return JSON.parse(localStorage.getItem(col) || '[]') } catch { return [] } },
  find:   (col, id) => db.get(col).find(r => r.id === id) || null,
  update: (col, id, patch) => {
    const records = db.get(col)
    const i = records.findIndex(r => r.id === id)
    if (i === -1) return null
    records[i] = { ...records[i], ...patch, updatedAt: new Date().toISOString() }
    localStorage.setItem(col, JSON.stringify(records))
    return records[i]
  },
  remove: (col, id) => {
    const filtered = db.get(col).filter(r => r.id !== id)
    localStorage.setItem(col, JSON.stringify(filtered))
    return true
  },
  clear: (col) => { localStorage.removeItem(col); return true },
}`
  }

  if (['backend', 'data'].includes(resolvedStack)) {
    files['shared/mock_db.py'] = `# shared/mock_db.py
# Zero-config JSON store — swap for real DB post-demo
# Usage: db.save('users', {'name': 'Alice'}) → returns saved record with id + createdAt
import json, os
from datetime import datetime, timezone

DB_PATH = '.mock_db.json'
def _load(): return json.load(open(DB_PATH)) if os.path.exists(DB_PATH) else {}
def _dump(d): json.dump(d, open(DB_PATH, 'w'), indent=2)

class _DB:
    def save(self, col, rec):
        d = _load(); d.setdefault(col, [])
        e = {'id': str(len(d[col])+1), 'createdAt': datetime.now(timezone.utc).isoformat(), **rec}
        d[col].append(e); _dump(d); return e
    def get(self, col): return _load().get(col, [])
    def clear(self, col): d = _load(); d.pop(col, None); _dump(d)

db = _DB()`
  }

  if (win === '3hr') {
    files['modes/hackathon.md'] = hackathonModeMd
  }

  if (deploy === 'pages' && ['frontend', 'fullstack'].includes(resolvedStack)) {
    files['vite.config.js'] = buildViteConfig()
  }

  return files
}
